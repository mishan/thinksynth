#!/usr/bin/env python3
"""cmudict -- write plugins/composer/cmudict.h, xform::say's dictionary.

The CMU Pronouncing Dictionary has about 135,000 words, most of them
names and rare forms; this keeps the ones in SCOWL's lists up to size
35 (its "small" dictionary, common words and their inflections), in US
and common spelling, and the first pronunciation of each.

    scripts/cmudict.py CMUDICT SCOWL_FINAL > plugins/composer/cmudict.h

CMUDICT is cmudict.dict and its LICENSE beside it, from
https://github.com/cmusphinx/cmudict; SCOWL_FINAL is the final/
directory of a SCOWL release, from http://wordlist.aspell.net, with its
Copyright and VERSION one level up; their notices are in
docs/THIRD_PARTY_NOTICES.txt too, which ships with the program. The
header in the tree was made
from cmudict at 74790861f652b15e4ac49015a90074ad62a27690 and SCOWL
2020.12.07.
"""

import os
import re
import sys

LEVEL = 35


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__.split("\n\n")[2])
    cmudict, final = sys.argv[1], sys.argv[2]

    words = set()
    for name in os.listdir(final):
        m = re.fullmatch(r"(english|american)-words\.(\d+)", name)
        if m and int(m.group(2)) <= LEVEL:
            with open(os.path.join(final, name), encoding="latin-1") as f:
                words.update(w.strip() for w in f if re.fullmatch(r"[a-z][a-z']*", w.strip()))

    said = {}
    with open(cmudict, encoding="utf-8") as f:
        for line in f:
            word, *phones = line.split("#")[0].split()
            if "(" not in word and word in words:
                said.setdefault(word, " ".join(phones))

    with open(os.path.join(os.path.dirname(cmudict), "LICENSE"), encoding="utf-8") as f:
        cmuLicense = f.read().strip()
    with open(os.path.join(final, "..", "Copyright"), encoding="latin-1") as f:
        scowlNotice = f.read().strip()
    with open(os.path.join(final, "..", "VERSION"), encoding="latin-1") as f:
        scowlVersion = f.read().strip()

    out = sys.stdout
    out.write("/* Generated by scripts/cmudict.py; do not edit.\n *\n")
    out.write(" * Words and pronunciations from the CMU Pronouncing Dictionary,\n")
    out.write(f" * chosen by SCOWL {scowlVersion}'s word lists. Their notices:\n *\n")
    for line in (cmuLicense + "\n\n" + scowlNotice).split("\n"):
        out.write((" * " + line).rstrip() + "\n")
    out.write(" */\n\n#ifndef TH_CMUDICT_H\n#define TH_CMUDICT_H 1\n\n")
    out.write("/* A word a line, upper case, sorted, then its ARPAbet. */\n")
    out.write("static const char englishDictionary[] =\n")
    for word in sorted(said, key=lambda w: w.upper()):
        out.write(f'    "{word.upper()} {said[word]}\\n"\n')
    out.write("    ;\n\n#endif\n")


if __name__ == "__main__":
    main()
